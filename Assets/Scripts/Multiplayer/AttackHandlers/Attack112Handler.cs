using System.Collections;
using UnityEngine;

/// <summary>
/// Attack ID 112: Jaguar Warriors
/// Shared playback owns damage and ATT debuff. This handler renders only the cast animation and dialog.
/// </summary>
public class Attack112Handler
{
    public static IEnumerator Execute(
        Kard attacker,
        Kard defender,
        int damage,
        bool isMyAttack,
        AttackAnimations animations,
        MultiplayerCardAnimator cardAnimator,
        HealthBar playerLifeBar,
        HealthBar enemyLifeBar,
        System.Func<string, IEnumerator> showDialog,
        string attackResult = null)
    {
        yield return showDialog($"{attacker.cardName} uses Jaguar Warriors");
        yield return animations.PlayJaguarWarriorsAnimation(attacker.transform, defender.transform);

        if (damage > 0)
        {
            yield return BattleValuePlayback.PlayDamage(
                defender,
                damage,
                !isMyAttack,
                cardAnimator,
                playerLifeBar,
                enemyLifeBar
            );
        }

        yield return showDialog($"{attacker.cardName} sends Jaguar Warriors");
    }
}
