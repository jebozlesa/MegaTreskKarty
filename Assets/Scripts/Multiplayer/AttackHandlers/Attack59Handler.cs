using System.Collections;
using UnityEngine;

/// <summary>
/// Attack ID 59: Justice Crusade
/// Simple attacker-cast animation with server-driven damage.
/// </summary>
public class Attack59Handler
{
    public static IEnumerator Execute(
        Kard attacker,
        Kard defender,
        int damage,
        bool isMyAttack,
        AttackAnimations animations,
        MultiplayerCardAnimator cardAnimator,
        HealthBar playerLifeBar,
        HealthBar enemyLifeBar,
        System.Func<string, IEnumerator> showDialog)
    {
        yield return showDialog($"{attacker.cardName} uses Justice Crusade");
        yield return animations.PlayJusticeCrusadeAnimation(attacker.transform);

        if (damage > 0)
        {
            yield return BattleValuePlayback.PlayDamage(
                defender,
                damage,
                !isMyAttack,
                cardAnimator,
                playerLifeBar,
                enemyLifeBar
            );
        }

        yield return showDialog($"{attacker.cardName} fights enemy for justice");
    }
}
